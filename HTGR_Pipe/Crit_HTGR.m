function Crit_HTGR()     %Функция поиска критической скорости гелия, при которой происходит потеря устойчивости трубопровода ВТГР
Data_HTGR
E=eye(8,8);
M=mu_eff*L2/420*[156/L2*L1+156 0 0 22*L2 54 0 0 -13*L2;
0 156/L2*L1+156 -22*L2 0 0 54 13*L2 0;
0 -22*L2 4/L2*L1^3+4*L2^2 0 0 -13*L2 -3*L2^2 0;
22*L2 0 0 4/L2*L1^3+4*L2^2 13*L2 0 0 -3*L2^2;
54 0 0 13*L2 156/L2*L3+156 0 0 -22*L2;
0 54 -13*L2 0 0 156/L2*L3+156 22*L2 0;
0 13*L2 -3*L2^2 0 0 22*L2 4/L2*L3^3+4*L2^2 0;
-13*L2 0 0 -3*L2^2 -22*L2 0 0 4/L2*L3^3+4*L2^2];
%Матрица собственной изгибной жесткости
K_0=EI/L2^3*[12+12*(L2/L1)^3 0 0 6*L2+6*L2^3/L1^2 -12 0 0 -6*L2;    
    0 12+12*(L2/L1)^3 -6*L2-6*L2^3/L1^2 0 0 -12 6*L2 0;
    0 -6*L2-6*L2^3/L1^2 4*L2^2+4*L2^3/L1 0 0 6*L2 -4*L2^2 0; 
    6*L2+6*L2^3/L1^2 0 0 4*L2^2+4*L2^3/L1 6*L2 0 0 -4*L2^2;
   -12 0 0 -6*L2 12+12*(L2/L3)^3 0 0 6*L2+6*L2^3/L3^2;
   0 -12 6*L2 0 0 12+12*(L2/L3)^3 -6*L2-6*L2^3/L3^2 0;
    0  6*L2 -4*L2^2 0 0 -6*L2-6*L2^3/L3^2 4*L2^2+4*L2^3/L3 0;
   -6*L2 0 0 -4*L2^2 6*L2+6*L2^3/L3^2 0 0 4*L2^2+4*L2^3/L3];
%Матрица термоупругого расширения 
K_t=N_t/(30*L2)*[36+36*L2/L1 0 0 3*L2+3*L2 -36 0 0 -3*L2;
    0 36+36*L2/L1 -3*L2-3*L2 0 0 -36 3*L2 0;
    0 -3*L2-3*L2 4*L2^2+4*L2*L1 0 0 3*L2 -4*L2^2 0;
    3*L2+3*L2 0 0 4*L2^2+4*L2*L1 -3*L2 0 0 -4*L2^2
    -36 0 0 -3*L2 36+36*L2/L3 0 0 3*L2+3*L2
    0 -36 3*L2 0 0 36+36*L2/L3 -3*L2-3*L2 0
    0 3*L2 -4*L2^2 0 0 -3*L2-3*L2 4*L2^2+4*L2*L1 0
    -3*L2 0 0 -4*L2^2 3*L2+3*L2 0 0 4*L2^2+4*L2*L3];
 
V_start = 0;
V_max = 150; % Верхняя граница скорост гелия в эксплуатационном диапазоне ВТГР
crit = 0;
V_crit = 0;
crit=0;
for V = V_start:1:V_max
    G=mu_f*V/30*[0 0 0 -6*L2 0 0 0 -6*L2;   %Матрица кориолисовых сил и моментов
    0 0 6*L2 0 0 0 6*L2 0;
    0 -6*L2 0 0 0 6*L2 0 -L2^2;
    6*L2 0 0 0 6*L2 0 L2^2 0;
    0 0 0 -6*L2 0 0 0 -6*L2
    0 0 -6*L2 0 0 0 6*L2 0;
    0 -6*L2 0 -L2^2 0 -6*L2 0 0;
    6*L2 0 L2^2 0 6*L2 0 0 0];
    K_f=K_t/(N_t/(30*L2))*mu_f*V^2/30/L2;       %Матрица потока гелия:
    K=K_0 - K_t/10-K_f;    %Матрица жесткости с учетом температурного расширения (с сильфоном) и движущегося потока гелия
    K = (K + K') / 2; % Защита от численной асимметрии
    G = (G - G') / 2; % Защита от численной асимметрии
    A=[zeros(8,8) E;-M^(-1)*K -M^(-1)*G];
    lambda = eig(A);    %Поиск комплексных собственных значений матрицы системы
    % Сканирование всего спектра системы на наличие положительной
    % вещественной части
    for j = 1:16
        if real(lambda(j)) >= 1e-3
            crit = 1;
            V_crit = V;
            break;
        end
    end
    
    if crit == 1
        break;
    end
end
% Вывод обоснованного заключения
fprintf('\n================== РЕЗУЛЬТАТЫ РАСЧЕТА ==================\n');
if crit == 0
    fprintf('Критическая скорость флаттера в диапазоне %d...%d м/с НЕ НАЙДЕНА.\n', V_start, V_max);
    fprintf('Контур трубопровода горячего гелия динамически стабилен.\n');
    fprintf('Текущий запас гидроупругой устойчивости по скорости: К_з = %.2f\n', V_max / 60);
else
    fprintf('ОБНАРУЖЕНА ПОТЕРЯ УСТОЙЧИВОСТИ при скорости потока V = %d м/с\n', V_crit);
end
fprintf('========================================================\n');