%%Скрипт solution_Centrifuge решения уравнений колебаний и построение траекторий, фазового портрета и сечений Пуанкаре для нелинейных колебаний ротора центрифуги ФГП; построение странного аттрактора
clear; clc; close all;
Data_Centrifuge 
options = odeset('RelTol', 1e-6, 'AbsTol', 1e-8);
Z0 = [0.001; 0.001; 0; 0]; % Стартовый толчок
% РАСЧЕТ ЧАСТОТ СИСТЕМЫ
omega_0 = sqrt(k0 / m); % Базовая линейная частота ротора
% Коэффициенты масштабирования нелинейных зон Дуффинга
w1 = round(0.693 * omega_0); % Режим 1: СУБГАРМОНИКА 1/3 (w = 31 рад/с)
w2 = round(1.140 * omega_0)*1.224; % Режим 2: ПЕРИОДИЧЕСКИЙ ЭЛЛИПС
w3 = round(1.677 * omega_0); % Режим 3:  ХАОС       (w = 75 рад/с)
e1 = 0.090;     % Эксцентриситеты под каждый режим
e2 = 0.020; 
e3 = 0.090; 
fig1 = figure('Name','Орбиты движения центра ротора центрифуги ФГП');
fig2 = figure('Name','Фазовые портреты и стробоскопические сечения Пуанкаре');
%% =========================================================================
%% БЛОК РАСЧЕТА РЕЖИМА 1. СУБГАРМОНИКА 1/3
%% =========================================================================
[t1, Z1] = ode45(@(t,Z) duff_Centrifuge(t, Z, m, b, k0,k1, e1, w1), [0 300], Z0, options);    %Решение уравнений колебаний
[t1, u1] = unique(t1); Z1 = Z1(u1, :);
figure(fig1); subplot(1,3,1); plot(Z1(t1>250,1), Z1(t1>250,2), 'b-', 'LineWidth', 1); grid on; axis equal;      %Построение траектории
xlabel('X, м'); ylabel('Y, м'); title(['Режим 1 (\omega = ', num2str(w1), ')']);
figure(fig2); subplot(2,3,1); plot(Z1(t1>250,1), Z1(t1>250,3), 'k-', 'LineWidth', 0.5); grid on;        %Построение фазового портрета
xlim([min(Z1(t1>250,1))*1.2, max(Z1(t1>250,1))*1.2]); ylim([min(Z1(t1>250,3))*1.2, max(Z1(t1>250,3))*1.2]);
xlabel('X, м'); ylabel('dx/dt, м/с'); title('Фазовый портрет 1');
T_p1 = 2*pi/w1; N1 = ceil(250 / T_p1); t_p1 = (N1 : 1 : N1 + 400) * T_p1; t_p1 = t_p1(t_p1 < t1(end));
x_p1 = interp1(t1, Z1(:,1), t_p1, 'linear'); y_p1 = interp1(t1, Z1(:,2), t_p1, 'linear');
subplot(2,3,4); plot(x_p1, y_p1, 'r.', 'MarkerSize', 14); grid on;             %Построение сечения Пуанкаре
xlim([min(Z1(t1>250,1))*1.2, max(Z1(t1>250,1))*1.2]); ylim([min(Z1(t1>250,2))*1.2, max(Z1(t1>250,2))*1.2]);
xlabel('X, м'); ylabel('Y, м'); title('Сечение Пуанкаре, режим 1');
%% =========================================================================
%% БЛОК РАСЧЕТА РЕЖИМА 2. ПЕРИОДИЧЕСКИЙ ЭЛЛИПС
%% =========================================================================
[t2, Z2] = ode45(@(t,Z) duff_Centrifuge(t, Z, m, b, k0, k1, e2, w2), [0 300], Z0, options);    %Решение уравнений колебаний
[t2, u2] = unique(t2); Z2 = Z2(u2, :);
figure(fig1); subplot(1,3,2); plot(Z2(t2>295,1), Z2(t2>295,2), 'b-', 'LineWidth', 1); grid on; axis equal;      %Построение траектории
xlabel('X, м'); ylabel('Y, м'); title(['Режим 2 (\omega = ', num2str(w2), ')']);
figure(fig2); subplot(2,3,2); plot(Z2(t2>250,1), Z2(t2>250,3), 'k-', 'LineWidth', 0.5); grid on;         %Построение фазового портрета
xlim([min(Z2(t2>250,1))*1.2, max(Z2(t2>250,1))*1.2]); ylim([min(Z2(t2>250,3))*1.2, max(Z2(t2>250,3))*1.2]);
xlabel('X, м'); ylabel('dx/dt, м/с'); title('Фазовый портрет 2');
T_p2 = 2*pi/w2; N2 = ceil(250 / T_p2); t_p2 = (N2 : 1 : N2 + 400) * T_p2; t_p2 = t_p2(t_p2 < t2(end));
x_p2 = interp1(t2, Z2(:,1), t_p2, 'linear'); y_p2 = interp1(t2, Z2(:,2), t_p2, 'linear');
subplot(2,3,5); plot(x_p2, y_p2, 'r.', 'MarkerSize', 14); grid on;              %Построение сечения Пуанкаре
xlim([min(Z2(t2>250,1))*1.2, max(Z2(t2>250,1))*1.2]); ylim([min(Z2(t2>250,2))*1.2, max(Z2(t2>250,2))*1.2]);
xlabel('X, м'); ylabel('Y, м'); title('Сечение Пуанкаре, режим 2');
%% =========================================================================
%% БЛОК РАСЧЕТА РЕЖИМА 3. РАЗВИТЫЙ ДЕТЕРМИНИРОВАННЫЙ ХАОС
%% =========================================================================
[t3, Z3] = ode45(@(t,Z) duff_Centrifuge(t, Z, m, b, k0, k1, e3, w3), [0 300], Z0, options);    %Решение уравнений колебаний
[t3, u3] = unique(t3); Z3 = Z3(u3, :);
figure(fig1); subplot(1,3,3); plot(Z3(t3>299,1), Z3(t3>299,2), 'b-', 'LineWidth', 1); grid on; axis equal;      %Построение траектории
xlabel('X, м'); ylabel('Y, м'); title(['Режим 3 (\omega = ', num2str(w3), ')']);        
figure(fig2); subplot(2,3,3); plot(Z3(t3>250,1), Z3(t3>250,3), 'k-', 'LineWidth', 0.5); grid on;        %Построение фазового портрета
xlim([min(Z3(t3>250,1))*1.2, max(Z3(t3>250,1))*1.2]); ylim([min(Z3(t3>250,3))*1.2, max(Z3(t3>250,3))*1.2]);
xlabel('X, м'); ylabel('dx/dt, м/с'); title('Фазовый портрет 3');
T_p3 = 2*pi/w3; N3 = ceil(250 / T_p3); t_p3 = (N3 : 1 : N3 + 400) * T_p3; t_p3 = t_p3(t_p3 < t3(end));
x_p3 = interp1(t3, Z3(:,1), t_p3, 'linear'); y_p3 = interp1(t3, Z3(:,2), t_p3, 'linear');
subplot(2,3,6); plot(x_p3, y_p3, 'r.', 'MarkerSize', 12); grid on;              %Построение сечения Пуанкаре
xlim([min(Z3(t3>250,1))*1.2, max(Z3(t3>250,1))*1.2]); ylim([min(Z3(t3>250,2))*1.2, max(Z3(t3>250,2))*1.2]);
xlabel('X, м'); ylabel('Y, м'); title('Сечение Пуанкаре, режим 3');
%% =========================================================================
%% БЛОК 2. СТРАННЫЙ АТТРАКТОР
%% =========================================================================
% Извлечение хаотического режима для построения 3D-аттрактора
w_ch = w3; e_ch = e3;
[t_c, Z_c] = ode45(@(t,Z) duff_Centrifuge(t, Z, m, b, k0, k1, e_ch, w_ch), [0 150], Z0, options);
idx_ch = t_c > 140; 
figure('Name','3D Странный аттрактор ротора центрифуги ФГП', 'Color', 'w'); 
plot3(Z_c(idx_ch,1), Z_c(idx_ch,2), Z_c(idx_ch,3), 'k-', 'LineWidth', 0.5); 
grid on; 
set(gca, 'Color', 'w', 'XColor', 'k', 'YColor', 'k', 'ZColor', 'k');
xlabel('Перемещение x, м', 'Color', 'k'); 
ylabel('Перемещение y, м', 'Color', 'k'); 
zlabel('Скорость dx/dt, м/с', 'Color', 'k');
title('3D Странный хаотический аттрактор Дуффинга для ротора центрифуги', 'Color', 'k');
view(35, 25); % Настройка пространственного угла обзора