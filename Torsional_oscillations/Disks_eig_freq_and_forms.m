% Script-файл поиска собственных частот и форм колебаний 4-х дискового вала (задача 1)
n = 4;
I_elements = [45.0, 15.0, 15.0, 30.0];          % Моменты инерции дисков, кг*м^2
c_elements = [3.5e5, 4.0e5, 3.0e5];             % Жесткости участков вала, Н*м/рад
delta_c = c_elements(1) / 1e5; 
I = diag(I_elements);     % 1. ФОРМИРОВАНИЕ ДИАГОНАЛЬНОЙ МАТРИЦЫ ИНЕРЦИИ (I)
C = zeros(n, n);    % 2. ФОРМИРОВАНИЕ ТРЕХДИАГОНАЛЬНОЙ МАТРИЦЫ ЖЕСТКОСТИ (C)
for i = 1:(n-1)     % Поэлементная сборка матрицы жесткости (ансамблирование)
    c_val = c_elements(i);
    C(i, i)     = C(i, i)     + c_val;          % Вклад текущего упругого участка вала в сопрягаемые узлы i и i+1
    C(i, i+1)   = C(i, i+1)   - c_val;
    C(i+1, i)   = C(i+1, i)   - c_val;
    C(i+1, i+1) = C(i+1, i+1) + c_val;
end
C(1,1) = C(1,1) + delta_c;    % Добавка мягких связей для 1-го и последнего (n-го) дисков
C(n,n) = C(n,n) + delta_c;
disp('Глобальная матрица инерции I (размерность 4х4):');
disp(I);
disp('Глобальная матрица жесткости C (размерность 4х4):');
disp(C);
% МЕТОД 1. ПРЯМАЯ ДИНАМИЧЕСКАЯ МАТРИЦА %% =========================================================================
A1 = inv(I) * C;      % Решаем задачу: (A1 - lambda*E)*V = 0, где A1 = inv(I)*C
[V1, L1] = eig(A1);
p_method1 = sqrt(diag(L1));   % Извлечение частот p (рад/с) из собственных чисел \lambda = p^2
[p_method1, sort_idx1] = sort(p_method1); % Сортировка по возрастанию спектра
V1 = V1(:, sort_idx1); % Перестроение форм согласно сортировке частот
% МЕТОД 2. СИММЕТРИЗОВАННАЯ МАТРИЦА 
I_sqrt_inv=diag(1 ./ sqrt(diag(I)));% Вычисление дробных матричных степеней I^(1/2) и I^(-1/2) через diag
I_sqrt=diag(sqrt(diag(I)));
A2 = I_sqrt_inv * C * I_sqrt_inv;    % Формирование симметричной матрицы A2 = I^(-1/2) * C * I^(-1/2)
[U2, L2] = eig(A2);
V2 = I_sqrt_inv * U2;    % Восстанавление истинных форм колебаний V2 = I^(-1/2) * U2
p_method2 = sqrt(diag(L2));
[p_method2, sort_idx2] = sort(p_method2);
V2 = V2(:, sort_idx2);
% МЕТОД 3. ОБРАТНАЯ МАТРИЦА ПОДАТЛИВОСТИ
A3 = inv(C) * I;
[V3, L3] = eig(A3);
p_method3 = sqrt(1 ./ diag(L3));    % Здесь собственные числа \lambda = 1 / p^2, поэтому p = sqrt(1 / \lambda)
[p_method3, sort_idx3] = sort(p_method3); % Сортировка спектра частот
V3 = V3(:, sort_idx3);
% СРАВНЕНИЕ РЕЗУЛЬТАТОВ И НОРМИРОВКА ФОРМ КОЛЕБАНИЙ 
fprintf('\n==================================================\n');
fprintf('   СРАВНИТЕЛЬНЫЙ АНАЛИЗ СОБСТВЕННЫХ ЧАСТОТ (рад/с) \n');
fprintf('==================================================\n');
fprintf('Мода |   Метод 1 (I^-1*C)  |  Метод 2 (Симметр)  |  Метод 3 (C^-1*I) \n');
for idx = 1:n
    fprintf('  %d  |    %12.4f   |    %12.4f     |    %12.4f \n', ...
            idx, p_method1(idx), p_method2(idx), p_method3(idx));
end
for idx = 1:n    % Выполняем принудительную евклидову нормировку ||V|| = 1 для всех форм
    V1(:, idx) = V1(:, idx) / norm(V1(:, idx));
    V2(:, idx) = V2(:, idx) / norm(V2(:, idx));
    V3(:, idx) = V3(:, idx) / norm(V3(:, idx));
end
disp(' ');
disp('Нормированные формы крутильных колебаний (по Методу 2):');
disp(V2);
% БЛОК ВИЗУАЛИЗАЦИИ СОБСТВЕННЫХ ФОРМ КРУТИЛЬНЫХ КОЛЕБАНИЙ
figure('Name', 'Собственные формы крутильных колебаний 4-хдискового вала', 'Color', 'w');
disk_indices = 1:n; % Вектор номеров дисков (ось абсцисс)
for mode_idx = 1:n
    subplot(2, 2, mode_idx);
    hold on; grid on; box on;
    plot(disk_indices, V1(:, mode_idx), 'b-o', 'LineWidth', 1.5, 'MarkerFaceColor', 'b');    % 1. Отрисовка формы по Методу 1 (Синяя сплошная линия с круглыми маркерами)
    plot(disk_indices, V2(:, mode_idx), 'r--x', 'LineWidth', 1.5, 'MarkerSize', 8);    % 2. Отрисовка формы по Методу 2 (Красная штриховая линия с крестиками)
    plot(disk_indices, V3(:, mode_idx), 'k:s', 'LineWidth', 1.2, 'MarkerFaceColor', 'none');  % 3. Отрисовка формы по Методу 3 (Черная пунктирная линия с квадратами)
    xlim([0.5, n + 0.5]);
    set(gca, 'XTick', disk_indices); % Отображаются строго целые номера дисков
    xlabel('Номер диска мешалки', 'FontSize', 10);
    ylabel('Нормированный угол поворота \theta, рад', 'FontSize', 10);
    title(['Форма колебаний №', num2str(mode_idx), ' (p = ', num2str(p_method2(mode_idx), '%.2f'), ' рад/с)'], 'FontSize', 11);
    if mode_idx == 1
        legend('Метод 1: I^{-1}C', 'Метод 2: Симметричный', 'Метод 3: C^{-1}I', 'Location', 'best');
    end
end